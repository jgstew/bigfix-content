#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# dependencies = ["besapi>=4.4.6"]
# ///
"""Build the Windows action templates in ../../actions/ from the repo's fixlets, with besapi.

Each template is the fixlet's default action as a SingleAction (besapi's action_xml_from_bes_file(), which keeps the
PowerShell script type from besapi 4.4.6), with this app's placeholders put in:
  - the fixlet's `computer name = "..."` guard becomes `computer name as lowercase = "{{Hostname}}" as lowercase`
  - the target is <ComputerID>{{ComputerID}}</ComputerID> alone
  - the title is "<label> from WebUI Custom App: {{Hostname}} ({{ComputerID}}) - {{Reason}}"
  - MIME fields record the app's source and the reason

The templates are committed, so pack.py needs only the standard library; run this again after changing a fixlet.

Usage (from this folder):
    uv run make_templates.py          write the templates
    uv run make_templates.py --check  exit 1 if a committed template differs from what the fixlet gives
"""

import argparse
import re
import sys
import tempfile
from pathlib import Path

import besapi.besapi
import lxml.etree

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
ACTIONS_DIR = REPO / "actions"

# (source fixlet, template file name, title label, value of x-deployment-webui-app-source)
TEMPLATES = [
    (
        "fixlet/Wipe Computer - MDM_RemoteWipe - Windows.bes",
        "Wipe_Windows_erase_everything_from_WebUI.bes.mustache",
        "Wipe Windows (erase everything)",
        "native-windows-wipe",
    ),
    (
        "fixlet/MDM/MDM Wipe Computer Persist Provisioned Data - Windows.bes",
        "Wipe_Windows_keep_provisioning_from_WebUI.bes.mustache",
        "Wipe Windows (keep provisioning)",
        "native-windows-wipe-keep-provisioning",
    ),
    (
        "fixlet/MDM/MDM Wipe Computer Persist User Data - Windows.bes",
        "Reset_Windows_keep_user_files_from_WebUI.bes.mustache",
        "Reset Windows (keep user files)",
        "native-windows-reset-keep-files",
    ),
    (
        "fixlet/Force BitLocker into Recovery - Destructive - Windows.bes",
        "BitLocker_force_recovery_from_WebUI.bes.mustache",
        "Force BitLocker recovery",
        "native-windows-bitlocker-recovery",
    ),
]

# the fixlets' hand-edited targeting guard, e.g. computer name = "WIN-ComputerNameToWipe" /* <-- ... */
GUARD_RE = re.compile(r'^\s*computer name\s*=\s*"[^"]*"\s*(/\*.*?\*/)?\s*$', re.S)
GUARD = 'computer name as lowercase = "{{Hostname}}" as lowercase'
PLACEHOLDERS = {"ComputerID", "Hostname", "Reason"}
# a computer ID no real target has, swapped for {{ComputerID}} after besapi builds the target
SENTINEL_ID = 2147483647


def fixlet_with_guard(source):
    """The fixlet's XML with its computer-name guard replaced by the {{Hostname}} check."""
    tree = lxml.etree.parse(str(source))
    guards = [r for r in tree.xpath("/BES/*/Relevance") if GUARD_RE.match(r.text or "")]
    if len(guards) != 1:
        sys.exit(f"ERROR: {source.name}: expected one `computer name = \"...\"` relevance, found {len(guards)}")
    guards[0].text = lxml.etree.CDATA(GUARD)
    return lxml.etree.tostring(tree, xml_declaration=True, encoding="UTF-8")


def build(rel_source, name, label, source_tag):
    source = REPO / rel_source
    with tempfile.TemporaryDirectory() as tmp:
        tmp_file = Path(tmp) / source.name
        tmp_file.write_bytes(fixlet_with_guard(source))
        xml = besapi.besapi.action_xml_from_bes_file(str(tmp_file), targets=SENTINEL_ID)

    def swap(old, new, text):
        if text.count(old) != 1:
            sys.exit(f"ERROR: {name}: expected {old!r} once in the action XML, found {text.count(old)}")
        return text.replace(old, new)

    xml = swap(f"<ComputerID>{SENTINEL_ID}</ComputerID>", "<ComputerID>{{ComputerID}}</ComputerID>", xml)
    xml = re.sub(r"<Title>.*?</Title>", lambda m: f"<Title><![CDATA[{label} from WebUI Custom App: {{{{Hostname}}}} ({{{{ComputerID}}}}) - {{{{Reason}}}}]]></Title>", xml, count=1)
    mime = "".join(
        f"\t\t<MIMEFieldSingleAction>\n\t\t\t<Name>{n}</Name>\n\t\t\t<Value>{v}</Value>\n\t\t</MIMEFieldSingleAction>\n"
        for n, v in [("x-deployment-webui-app-source", source_tag), ("x-deployment-webui-app-reason", "<![CDATA[{{Reason}}]]>")]
    )
    xml = swap("\t</SingleAction>", mime + "\t</SingleAction>", xml)
    xml = swap(
        "<BES ",
        f"<!-- Generated by webui_apps/destructive-device-actions/make_templates.py from {rel_source}; edit the fixlet and run it again. -->\n<BES ",
        xml,
    )
    check(name, xml)
    return xml


def check(name, xml):
    """The template uses only the app's placeholders, and with them filled in it is valid BES XML for one computer."""
    used = set(re.findall(r"\{\{\s*(\w+)\s*\}\}", xml))
    if used != PLACEHOLDERS:
        sys.exit(f"ERROR: {name}: placeholders {sorted(used)}, expected {sorted(PLACEHOLDERS)}")
    sample = xml.replace("{{ComputerID}}", "12345").replace("{{Hostname}}", "SAMPLE-PC").replace("{{Reason}}", "TICKET-1")
    if not besapi.besapi.validate_xsd(sample.encode("utf-8")):
        sys.exit(f"ERROR: {name}: the filled-in template does not validate against BES.xsd")
    doc = lxml.etree.fromstring(sample.encode("utf-8"))
    ids = doc.xpath("/BES/SingleAction/Target/*")
    if len(doc.xpath("/BES/*")) != 1 or [(e.tag, e.text) for e in ids] != [("ComputerID", "12345")]:
        sys.exit(f"ERROR: {name}: must be one SingleAction targeting <ComputerID>{{{{ComputerID}}}}</ComputerID> alone")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the committed templates, write nothing")
    args = parser.parse_args()

    print(f"besapi {besapi.besapi.__version__}")
    stale = []
    for rel_source, name, label, source_tag in TEMPLATES:
        xml = build(rel_source, name, label, source_tag)
        out = ACTIONS_DIR / name
        current = out.read_text(encoding="utf-8") if out.is_file() else None
        if args.check:
            print(f"{'ok     ' if current == xml else 'STALE  '} actions/{name}")
            if current != xml:
                stale.append(name)
        elif current == xml:
            print(f"unchanged actions/{name}")
        else:
            out.write_text(xml, encoding="utf-8", newline="\n")
            print(f"wrote     actions/{name}")
    if stale:
        sys.exit(f"{len(stale)} template(s) out of date: run make_templates.py")


if __name__ == "__main__":
    main()
